<#
.SYNOPSIS
    Regenerate build\requirements-searxng.txt (hash-locked SearXNG dependencies).

.DESCRIPTION
    Resolves build\requirements-searxng.in (upstream requirements.txt at the pinned SearXNG
    commit, plus the AI-Hotkeys additions) for CPython 3.13 / win_amd64, wheels only, with
    build\constraints-searxng.txt keeping transitive versions on the tested set.
    Uses `uv pip compile --generate-hashes` (equivalent to pip-compile --generate-hashes).
    Run it only when bumping a pin; build.ps1 never re-resolves.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File build\lock-searxng.ps1
#>
param(
    [string]$Uv = 'uv'
)

$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$header = @(
    '# Hash-locked SearXNG dependencies for the AI-Hotkeys payload (CPython 3.13, win_amd64).'
    '# GENERATED by build\lock-searxng.ps1 from requirements-searxng.in + constraints-searxng.txt.'
    '# Do not edit by hand. Installed by build\build.ps1 with --require-hashes, wheels only.'
)
$body = & $Uv pip compile requirements-searxng.in -c constraints-searxng.txt `
    --generate-hashes --python-version 3.13 --python-platform x86_64-pc-windows-msvc `
    --no-build --no-header --annotation-style line --quiet
if ($LASTEXITCODE -ne 0) { throw "uv pip compile failed ($LASTEXITCODE)" }

$text = (($header + $body) -join "`n") + "`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'requirements-searxng.txt'), $text, (New-Object Text.UTF8Encoding $false))
Write-Host 'Wrote build\requirements-searxng.txt'
